-- Master products: one product (for example "Lint Machine") groups several channel SKUs. The Forecasting tab can
-- show a product's Flipkart SKUs combined.
--
--   master_products  one row per product, the name is unique
--   sku_master       which product a channel SKU belongs to; each SKU belongs to one product only. The SKU is kept
--                    exactly as written (spaces included); the app matches exact first, then any case.
--
-- Everyone signed in may read it (product names only). Nobody writes from the app directly: the owner replaces
-- the whole list through replace_master_skus (next migration). Seeded here from
-- supabase/seed-data/master_sku_mapping.csv (121 products, 433 SKUs), generated with
-- `node scripts/master-sku-seed.mjs supabase/seed-data/master_sku_mapping.csv`.

create table public.master_products (
  id uuid primary key default gen_random_uuid(),
  name text not null unique check (length(btrim(name)) between 1 and 200),
  created_at timestamptz not null default now()
);

create table public.sku_master (
  channel_sku text primary key check (length(btrim(channel_sku)) >= 1 and length(channel_sku) <= 200),
  master_id uuid not null references public.master_products (id) on delete cascade,
  updated_at timestamptz not null default now()
);
create index sku_master_master_idx on public.sku_master (master_id);

alter table public.master_products enable row level security;
alter table public.sku_master enable row level security;
revoke all on public.master_products, public.sku_master from anon, authenticated;
grant select on public.master_products, public.sku_master to authenticated;
grant all on public.master_products, public.sku_master to service_role;

create policy master_products_select on public.master_products for select to authenticated
  using ((select private.user_role()) is not null);
create policy sku_master_select on public.sku_master for select to authenticated
  using ((select private.user_role()) is not null);

